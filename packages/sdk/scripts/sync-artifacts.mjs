// Regenerates src/generated/abis.ts from the contracts repo's forge
// artifacts. Run after any contract change: `node scripts/sync-artifacts.mjs`
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const outDir = join(here, "../../../contracts/out");

const contracts = {
  hawkRegistryAbi: "HawkRegistry.sol/HawkRegistry.json",
  hawkBaseRegistrarAbi: "HawkBaseRegistrar.sol/HawkBaseRegistrar.json",
  hawkRegistrarControllerAbi:
    "HawkRegistrarController.sol/HawkRegistrarController.json",
  hawkPriceOracleAbi: "HawkPriceOracle.sol/HawkPriceOracle.json",
  hawkWrapperAbi: "HawkWrapper.sol/HawkWrapper.json",
  hawkReservedListAbi: "HawkReservedList.sol/HawkReservedList.json",
  hawkMetadataAbi: "HawkMetadata.sol/HawkMetadata.json",
  publicResolverAbi: "PublicResolver.sol/PublicResolver.json",
  reverseRegistrarAbi: "ReverseRegistrar.sol/ReverseRegistrar.json",
  universalResolverAbi: "UniversalResolver.sol/UniversalResolver.json",
};

let out = `// Generated by scripts/sync-artifacts.mjs — do not edit by hand.\n`;
for (const [name, path] of Object.entries(contracts)) {
  const artifact = JSON.parse(readFileSync(join(outDir, path), "utf8"));
  out += `\nexport const ${name} = ${JSON.stringify(
    artifact.abi,
    null,
    2,
  )} as const;\n`;
}
writeFileSync(join(here, "../src/generated/abis.ts"), out);
console.log(
  `wrote ${Object.keys(contracts).length} ABIs to src/generated/abis.ts`,
);
