// Regenerates src/generated/deployments.ts from the contracts repo's
// deployment records. Run after any deploy: node scripts/sync-addresses.mjs
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const deploymentsDir = join(here, "../../../contracts/deployments");

const networks = {
  local: "robin-local.json",
  "robinhood-testnet": "robin-robinhood-testnet.json",
  robinhood: "robin-robinhood.json",
};

const out = {};
for (const [key, file] of Object.entries(networks)) {
  const path = join(deploymentsDir, file);
  if (existsSync(path)) out[key] = JSON.parse(readFileSync(path, "utf8"));
}

mkdirSync(join(here, "../src/generated"), { recursive: true });
writeFileSync(
  join(here, "../src/generated/deployments.ts"),
  `// Generated by scripts/sync-addresses.mjs — do not edit by hand.\n` +
    `export const DEPLOYMENTS = ${JSON.stringify(out, null, 2)} as const;\n`,
);
console.log(`wrote deployments for: ${Object.keys(out).join(", ")}`);
